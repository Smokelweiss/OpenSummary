#!/usr/bin/env node
/**
 * Offline structural benchmark for the AI pipeline.
 *
 * It runs the real `runAiSummary` with a fake provider, so no key, network or
 * quota is involved. Every fake call answers after the same `--delay`, which
 * makes the measured wall clock a linear function of the number of sequential
 * waves. That is what this tool reports:
 *
 *   - how many requests the pipeline actually makes for a given transcript,
 *   - how many sequential waves they form (the model-independent part),
 *   - how many hierarchical reduce rounds happen,
 *   - when the first usable fragment appears,
 *   - what the critical path would cost at a given per-call latency.
 *
 * The last column is a projection with stated assumptions, not a measurement
 * of any real provider. Real API runs stay in `npm run bench -- --live`.
 *
 *   node tools/bench-sim.mjs --minutes=50
 *   node tools/bench-sim.mjs --minutes=104 --force=map-reduce
 *   node tools/bench-sim.mjs --minutes=50 --delay=150 --sweep=5000,10000,20000
 */

import { runAiSummary } from '../src/ai/pipeline.js';
import { providerFromPreset } from '../src/ai/providers.js';
import { countWords } from '../src/common/util.js';

const args = Object.fromEntries(
  process.argv.slice(2).map((arg) => {
    const [key, value] = arg.replace(/^--/, '').split('=');
    return [key, value === undefined ? true : value];
  }),
);

const minutes = Math.max(5, Number(args.minutes) || 50);
const delayMs = Math.max(0, Number(args.delay ?? 120));
const concurrency = Math.max(1, Number(args.concurrency) || 6);
const contextTokens = Math.max(4000, Number(args.context) || 128000);
const chunkTokens = Math.max(1500, Number(args.chunk) || 6000);
const force = String(args.force || 'auto');
const sweep = String(args.sweep || '5000,10000,20000')
  .split(',')
  .map((v) => Number(v))
  .filter((v) => v > 0);
const jsonOut = !!args.json;

/** ~150 words per minute of Russian speech, with timecodes. */
function fixture(min) {
  const topics = [
    'индексы и планы запросов',
    'транзакции и уровни изоляции',
    'репликация и отставание реплик',
    'очереди и повторные доставки',
    'наблюдаемость и трассировка',
    'профилирование горячих путей',
    'кэширование и инвалидация',
    'миграции без простоя',
  ];
  const segments = [];
  let at = 0;
  let i = 0;
  while (at < min * 60) {
    const words = 12 + ((i * 7) % 9);
    const topic = topics[i % topics.length];
    const text = `На шаге ${i + 1} разбираем ${topic}: решение важно измерить до внедрения, потому что цена ошибки здесь выше, чем экономия.`;
    segments.push({ start: at, dur: Math.max(2, Math.round(words / 2.5)), text });
    at += Math.max(2, Math.round(words / 2.5));
    i++;
  }
  return segments;
}

const segments = fixture(minutes);
const meta = {
  videoId: 'bench-sim',
  videoTitle: `Synthetic ${minutes} min`,
  channel: 'OpenSummary',
  lengthSeconds: minutes * 60,
  lang: 'ru',
  source: 'benchmark',
  autoGenerated: true,
  url: '',
};

/** A map note of roughly the same shape a real model returns. */
function note(index) {
  const topics = ['индексы', 'транзакции', 'репликация', 'очереди', 'наблюдаемость', 'кэш'];
  return {
    tldr: `Фрагмент ${index}: разобраны ${topics[index % topics.length]} и их влияние на задержку.`,
    points: Array.from({ length: 6 }, (_, k) => ({
      at: `00:${String((index + k) % 60).padStart(2, '0')}`,
      text: `Пункт ${k + 1} фрагмента ${index}: конкретное наблюдение про ${topics[(index + k) % topics.length]}, с условием применимости и ограничением.`,
    })),
    topics: [topics[index % topics.length]],
    facts: [`Фрагмент ${index} содержит числовой пример и оговорку о нагрузке.`],
  };
}

const calls = [];
let active = 0;
let maxActive = 0;
const startedAt = Date.now();
const progress = [];

const realFetch = globalThis.fetch;
globalThis.fetch = async (url, init = {}) => {
  const body = JSON.parse(String(init.body || '{}'));
  const call = { at: Date.now() - startedAt, max: body.max_tokens || 0, stream: !!body.stream };
  active++;
  maxActive = Math.max(maxActive, active);
  calls.push(call);
  await new Promise((resolve) => setTimeout(resolve, delayMs));
  active--;
  call.ms = Date.now() - startedAt - call.at;
  const content = JSON.stringify(note(calls.length));
  if (body.stream) {
    const enc = new TextEncoder();
    const stream = new ReadableStream({
      start(controller) {
        const payload = { choices: [{ delta: { content }, finish_reason: 'stop' }], model: 'sim-model' };
        controller.enqueue(enc.encode(`data: ${JSON.stringify(payload)}\n\n`));
        controller.enqueue(enc.encode('data: [DONE]\n\n'));
        controller.close();
      },
    });
    return new Response(stream, { status: 200, headers: { 'content-type': 'text/event-stream' } });
  }
  return new Response(
    JSON.stringify({
      choices: [{ message: { content }, finish_reason: 'stop' }],
      usage: { prompt_tokens: 1000, completion_tokens: 300 },
      model: 'sim-model',
    }),
    { status: 200, headers: { 'content-type': 'application/json' } },
  );
};

let result = null;
let diagnostics = null;
let error = null;
const started = Date.now();
try {
  const out = await runAiSummary({
    segments,
    meta,
    provider: providerFromPreset('openrouter'),
    apiKey: 'sim',
    model: 'sim-model',
    aiSettings: {
      strategy: force,
      contextTokens,
      chunkTokens,
      concurrency,
      stream: true,
      retries: 0,
      allowRateRetry: false,
      allowFormatRetry: false,
      jsonRepair: false,
      singleFallback: false,
      timeoutMs: 120000,
    },
    output: { language: 'ru', length: 'standard', tone: 'neutral' },
    uiLang: 'ru',
    onProgress: (event) => progress.push({ ...event, at: Date.now() - started }),
  });
  result = out.result;
  diagnostics = out.diagnostics;
} catch (err) {
  error = err;
} finally {
  globalThis.fetch = realFetch;
}
const wallMs = Date.now() - started;

const mapCalls = calls.length - (diagnostics?.requests || 0);
const reduceCalls = (diagnostics?.chunks || []).filter((c) => String(c.stage).startsWith('reduce')).length;
const singleCalls = (diagnostics?.chunks || []).filter((c) => c.stage === 'single').length;
const mapStageCalls = (diagnostics?.chunks || []).filter((c) => c.stage === 'map').length;
const mapWaves = mapStageCalls ? Math.ceil(mapStageCalls / concurrency) : 0;
const reduceRounds = diagnostics?.reduceRounds || 0;
const finalReduce = singleCalls ? 1 : reduceCalls > 0 ? 1 : 0;
const chain = mapWaves + reduceRounds + finalReduce;
const firstPartial = diagnostics?.firstPartialMs || 0;
const wordCount = countWords(segments.map((s) => s.text).join(' '));

const projection = sweep.map((lat) => ({
  perCallMs: lat,
  criticalPathMs: chain * lat,
  firstPartialMs: mapWaves ? lat : singleCalls ? lat : 0,
}));

const report = {
  mode: 'offline-structural',
  transcript: { minutes, sentences: segments.length, words: wordCount },
  settings: { strategy: force, contextTokens, chunkTokens, concurrency, fakeDelayMs: delayMs },
  strategy: diagnostics?.strategy || '',
  complete: diagnostics?.complete,
  requests: diagnostics?.requests || calls.length,
  byStage: {
    single: singleCalls,
    map: mapStageCalls,
    reduceBatch: (diagnostics?.chunks || []).filter((c) => c.stage === 'reduce-batch').length,
    reduce: (diagnostics?.chunks || []).filter((c) => c.stage === 'reduce').length,
  },
  chunks: diagnostics?.chunkCounts?.done ?? 0,
  chunkTotal: (diagnostics?.chunks || []).filter((c) => c.stage === 'map').length,
  reduceRounds,
  mapWaves,
  chain,
  maxActive,
  wallMs,
  firstPartialMs: firstPartial,
  stagesMs: diagnostics?.stageMs || {},
  tokens: diagnostics?.transcriptTokens || 0,
  projection,
  error: error ? { code: error.code || 'ERROR', message: String(error.message).slice(0, 300) } : null,
  tldrLen: result?.tldr?.length || 0,
};

if (jsonOut) {
  console.log(JSON.stringify(report, null, 2));
} else {
  console.log(`\n${minutes} min transcript · ${wordCount} words · ~${report.tokens} tokens`);
  console.log(`strategy: ${report.strategy} | requests: ${report.requests} | complete: ${report.complete}`);
  console.log(
    `by stage: single ${report.byStage.single} · map ${report.byStage.map} · reduce-batch ${report.byStage.reduceBatch} · reduce ${report.byStage.reduce}`,
  );
  console.log(`map waves @${concurrency}: ${mapWaves} | reduce rounds: ${reduceRounds} | critical path: ${chain} calls`);
  console.log(
    `wall ${wallMs} ms (fake ${delayMs} ms/call) | first partial ${firstPartial} ms | max parallel ${maxActive}`,
  );
  console.log(`projected at fixed per-call latency: ${projection.map((p) => `${p.perCallMs / 1000}s→${(p.criticalPathMs / 1000).toFixed(1)}s`).join(' · ')}`);
  if (error) console.log(`error: ${report.error.code} — ${report.error.message}`);
  console.log('projection assumes equal per-call latency, no 429, no retries; it is not an API measurement.\n');
}

process.exit(error ? 1 : 0);
