/**
 * Transcript orchestration in the service worker: video bundle (metadata,
 * caption tracks, chapters) + transcript segments, both memoised in memory.
 */

import {
  getVideoData,
  fetchTimedText,
  fetchInnertubeTranscript,
  fetchLegacyTimedText,
  pickTrack,
  isPoTokenProtected,
} from '../transcript/youtube.js';
import { getCachedTranscript, setCachedTranscript, transcriptKey } from './state.js';
import { cleanCaptionText, detectLang } from '../nlp/tokenize.js';
import { recordJournal } from '../common/journal.js';

const bundles = new Map(); // videoId -> {at, meta, chapters, tracks}
const BUNDLE_TTL = 10 * 60 * 1000;
const MAX_BUNDLES = 8;

export async function loadBundle(videoId, { force = false, hl = 'en' } = {}) {
  const hit = bundles.get(videoId);
  if (!force && hit && Date.now() - hit.at < BUNDLE_TTL) return hit.bundle;
  const data = await getVideoData(videoId, { hl });
  const bundle = {
    meta: data.meta,
    chapters: data.chapters,
    tracks: data.tracks,
    transcriptParams: data.transcriptParams || '',
    innertube: data.innertube || { clientVersion: '', visitorData: '' },
  };
  bundles.set(videoId, { at: Date.now(), bundle });
  while (bundles.size > MAX_BUNDLES) bundles.delete(bundles.keys().next().value);
  return bundle;
}

export function clearBundleCache() {
  bundles.clear();
}

function makeError(code, message, hint) {
  const err = new Error(message);
  err.code = code;
  err.hint = hint || '';
  return err;
}

/**
 * Returns transcript segments + enriched meta.
 * Throws with codes: NO_CAPTIONS, POT_REQUIRED, EMPTY_CAPTIONS, RATE_LIMITED,
 * CONSENT, NETWORK.
 */
export async function loadTranscript({
  videoId,
  lang = 'auto',
  preferManual = true,
  translate = true,
  force = false,
  hl = 'en',
} = {}) {
  if (!videoId) throw makeError('BAD_VIDEO_ID', 'Не удалось определить видео');
  const key = transcriptKey({ videoId, lang, kind: preferManual ? 'manual' : 'auto', translate });
  if (!force) {
    const cached = getCachedTranscript(key);
    if (cached) return { ...cached, cached: true };
  }

  const bundle = await loadBundle(videoId, { force, hl });
  const { meta, chapters, tracks, transcriptParams } = bundle;

  const buildPayload = ({ segments, format, trackLang, translated, autoGenerated, source, lang: detected, route = 'timedtext' }) => {
    recordJournal({
      level: 'ok',
      route,
      videoId,
      segments: segments.length,
      lang: detected || meta.lang || '',
      message: `${source}${format ? ` · ${format}` : ''}`,
    });
    const payload = {
      videoId,
      segments,
      format,
      cached: false,
      tracks: tracks.map((t) => ({ lang: t.lang, name: t.langName, auto: t.auto })),
      meta: {
        ...meta,
        videoId,
        lang: detected || meta.lang || 'ru',
        trackLang: trackLang || '',
        translated: !!translated,
        autoGenerated: !!autoGenerated,
        source,
        chapters,
        wordCount: segments.reduce((a, s) => a + s.text.split(/\s+/).length, 0),
        url: `https://www.youtube.com/watch?v=${videoId}`,
      },
    };
    setCachedTranscript(key, payload);
    return payload;
  };

  // Last resort before giving up: InnerTube's own get_transcript, the call the
  // page panel makes. It needs no PO token and no DOM scraping.
  const fromInnertube = async () => {
    if (!transcriptParams) {
      recordJournal({
        level: 'warn',
        route: 'get_transcript',
        videoId,
        code: 'NO_PARAMS',
        message: 'в данных страницы нет getTranscriptEndpoint.params',
      });
      return null;
    }
    try {
      const segments = await fetchInnertubeTranscript(transcriptParams, {
        hl,
        clientVersion: bundle.innertube?.clientVersion || '',
        visitorData: bundle.innertube?.visitorData || '',
      });
      if (segments.length < 2) {
        recordJournal({
          level: 'warn',
          route: 'get_transcript',
          videoId,
          segments: segments.length,
          message: 'ответ без сегментов',
        });
        return null;
      }
      const { lang: detected } = detectLang(segments.slice(0, 80).map((s) => s.text).join(' '));
      return buildPayload({
        segments,
        format: 'innertube',
        autoGenerated: false,
        source: 'captions-ui',
        lang: detected === 'ru' ? 'ru' : 'en',
        route: 'get_transcript',
      });
    } catch (err) {
      recordJournal({
        level: 'error',
        route: 'get_transcript',
        videoId,
        code: err?.code ? `HTTP_${err.code}` : 'REQUEST_FAILED',
        status: err?.code,
        message: String(err?.message || err).slice(0, 140),
      });
      return null;
    }
  };

  // Third route, independent of both the player and the page: the legacy
  // caption endpoint. It is the only one left when every track is `exp=xpe`
  // and the panel API refuses the request.
  const fromLegacy = async () => {
    const wanted = lang && lang !== 'auto' ? lang.slice(0, 2) : '';
    const langs = [];
    if (wanted) langs.push(wanted);
    for (const t of tracks) {
      const code = String(t.lang || '').slice(0, 2);
      if (code && !langs.includes(code)) langs.push(code);
    }
    langs.push('');
    for (const code of langs.slice(0, 3)) {
      for (const kind of ['', 'asr']) {
        try {
          const segments = await fetchLegacyTimedText(videoId, { lang: code, kind });
          if (segments.length < 2) continue;
          const { lang: detected } = detectLang(segments.slice(0, 80).map((s) => s.text).join(' '));
          recordJournal({
            level: 'ok',
            route: 'legacy-timedtext',
            videoId,
            segments: segments.length,
            message: `lang=${code || 'any'} kind=${kind || 'manual'}`,
          });
          return buildPayload({
            segments,
            format: 'legacy',
            trackLang: code,
            autoGenerated: kind === 'asr',
            source: kind === 'asr' ? 'captions-auto:legacy' : 'captions-manual:legacy',
            lang: detected === 'ru' ? 'ru' : 'en',
            route: 'legacy-timedtext',
          });
        } catch (err) {
          recordJournal({
            level: 'warn',
            route: 'legacy-timedtext',
            videoId,
            code: err?.code ? String(err.code) : 'REQUEST_FAILED',
            message: `lang=${code || 'any'} kind=${kind || 'manual'}: ${String(err?.message || err)}`.slice(0, 160),
          });
        }
      }
    }
    return null;
  };

  if (!tracks.length) {
    recordJournal({ level: 'warn', route: 'timedtext', videoId, code: 'NO_TRACKS', message: 'плеер не отдал ни одной дорожки' });
    const viaApi = (await fromInnertube()) || (await fromLegacy());
    if (viaApi) return viaApi;
    recordJournal({ level: 'error', route: 'resolve', videoId, code: 'NO_CAPTIONS', message: 'транскрипт недоступен ни одним из путей' });
    throw makeError(
      'NO_CAPTIONS',
      'У этого видео нет субтитров',
      'OpenSummary работает по субтитрам (в том числе автоматическим). Если у видео их нет, можно вставить текст вручную в разделе «Транскрипт».',
    );
  }

  const wanted = lang && lang !== 'auto' ? lang.slice(0, 2) : '';
  // PO-token-protected tracks always answer with an empty body from here, so the
  // transcript has to come from the panel API or from the page instead.
  const usable = tracks.filter((t) => !isPoTokenProtected(t));
  if (!usable.length) {
    recordJournal({ level: 'warn', route: 'timedtext', videoId, code: 'POT_REQUIRED', message: `все дорожки защищены (${tracks.length})` });
    const viaApi = (await fromInnertube()) || (await fromLegacy());
    if (viaApi) return viaApi;
    recordJournal({ level: 'error', route: 'resolve', videoId, code: 'POT_REQUIRED', message: 'ни get_transcript, ни timedtext не отдали текст' });
    throw makeError(
      'POT_REQUIRED',
      'YouTube не отдал текст субтитров: дорожка защищена PO-token',
      'Такие субтитры отдаёт только плеер на самой странице. Нажмите «Взять транскрипт со страницы» — OpenSummary прочитает панель «Транскрипт» на видео, либо вставьте текст вручную в разделе «Транскрипт».',
    );
  }
  let track = pickTrack(usable, { lang, preferManual });
  if (!track) {
    // pickTrack always returns an entry for a non-empty list, so this only fires
    // if that rule changes. The journal must say which step failed instead of
    // looking like “no captions at all”.
    recordJournal({
      level: 'error',
      route: 'timedtext',
      videoId,
      code: 'NO_TRACK_SELECTED',
      message: `дорожек ${usable.length}, ни одна не выбрана`,
    });
    throw makeError(
      'NO_TRACK_SELECTED',
      'Не удалось выбрать дорожку субтитров',
      'Попробуйте «Взять транскрипт со страницы» или вставьте текст вручную в разделе «Транскрипт».',
    );
  }
  const tlang = wanted && track && track.lang.slice(0, 2) !== wanted && translate ? wanted : '';

  let segments = [];
  let format = '';
  let usedTrack = track;
  let lastError = null;
  const attemptErrors = [];

  const attempt = async (candidate, fmt, withTlang) => {
    const parsed = await fetchTimedText(candidate, { fmt, tlang: withTlang || '' });
    if (parsed.segments.length) return parsed;
    return null;
  };

  const order = [track, ...usable.filter((t) => t !== track)];
  for (const candidate of order) {
    const useTlang = candidate === track ? tlang : '';
    for (const fmt of ['json3', 'vtt']) {
      try {
        const parsed = await attempt(candidate, fmt, useTlang);
        if (parsed) {
          segments = parsed.segments;
          format = parsed.format;
          usedTrack = candidate;
          break;
        }
      } catch (err) {
        lastError = err;
        attemptErrors.push({ fmt, code: err?.code || 'REQUEST_FAILED', message: String(err?.message || err) });
      }
    }
    if (segments.length) break;
  }

  if (!segments.length) {
    // Three different situations share this branch and must not look alike in
    // the journal: the download was refused, the body was empty, or the body
    // arrived and the parser produced no segments (the only parser-side defect).
    const parseError = attemptErrors.find((entry) => entry.code === 'PARSE_FAILED');
    const summary = attemptErrors.length
      ? attemptErrors.map((entry) => `${entry.fmt}:${entry.code}`).join(' · ')
      : 'пустой ответ без ошибки';
    const code = parseError ? 'PARSE_FAILED' : lastError?.code || 'EMPTY_CAPTIONS';
    recordJournal({
      level: 'warn',
      route: 'timedtext',
      videoId,
      code,
      message: `${summary}${parseError ? ` · ${parseError.message}` : lastError ? ` · ${lastError.message}` : ''}`.slice(0, 160),
    });
    const viaApi = (await fromInnertube()) || (await fromLegacy());
    if (viaApi) return viaApi;
    let err;
    if (parseError) {
      err = lastError && lastError.code === 'PARSE_FAILED'
        ? lastError
        : makeError(
            'PARSE_FAILED',
            parseError.message,
            'YouTube отдал текст субтитров, но разобрать его не удалось. Нажмите «Взять транскрипт со страницы» или вставьте текст вручную в разделе «Транскрипт».',
          );
    } else {
      err = lastError || makeError('EMPTY_CAPTIONS', 'Дорожка субтитров пуста');
    }
    recordJournal({ level: 'error', route: 'resolve', videoId, code: err.code, message: String(err.message).slice(0, 140) });
    throw err;
  }

  return buildPayload({
    segments,
    format,
    trackLang: usedTrack.lang,
    translated: tlang,
    autoGenerated: !!usedTrack.auto,
    lang: tlang || usedTrack.lang || lang,
    source: `${usedTrack.auto ? 'captions-auto' : 'captions-manual'}${tlang ? `+translate:${tlang}` : ''}${format ? `:${format}` : ''}`,
  });
}

/** Accepts either a transcript payload, inline segments or a videoId. */
export async function ensureTranscript(input = {}) {
  if (Array.isArray(input.segments) && input.segments.length) {
    const segments = input.segments
      .map((s) => ({ start: Number(s.start) || 0, dur: Number(s.dur) || 2, text: cleanCaptionText(s.text || '') }))
      .filter((s) => s.text);
    if (!segments.length) throw makeError('EMPTY_TRANSCRIPT', 'Транскрипт пуст');
    const videoId = input.videoId || input.meta?.videoId || '';
    return {
      videoId,
      segments,
      format: 'inline',
      tracks: [],
      meta: {
        videoId,
        videoTitle: input.meta?.videoTitle || '',
        channel: input.meta?.channel || '',
        lengthSeconds: Number(input.meta?.lengthSeconds) || 0,
        lang: input.meta?.lang || 'ru',
        source: input.meta?.source || 'inline',
        autoGenerated: !!input.meta?.autoGenerated,
        chapters: input.meta?.chapters || [],
        url: videoId ? `https://www.youtube.com/watch?v=${videoId}` : '',
        description: input.meta?.description || '',
        wordCount: segments.reduce((a, s) => a + s.text.split(/\s+/).length, 0),
      },
    };
  }
  if (!input.videoId) throw makeError('BAD_VIDEO_ID', 'Не удалось определить видео');
  return loadTranscript({
    videoId: input.videoId,
    lang: input.lang,
    preferManual: input.preferManual,
    translate: input.translate,
    force: input.force,
  });
}
